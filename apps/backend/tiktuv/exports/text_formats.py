"""Plain text, timestamped text, SRT, VTT and JSON exporters."""

from __future__ import annotations

import json
from pathlib import Path

from ..schemas import ExportFormat
from ..text.hebrew import (
    RLM,
    format_clock,
    format_timestamp,
    paragraph_text,
    protect_neutrals,
    split_paragraphs,
)
from ..text.subtitles import build_cues
from .base import ExportContext, target_path, write_text


class TxtExporter:
    """Plain Hebrew text, paragraphs separated by a blank line."""

    format = ExportFormat.TXT
    extension = "txt"

    def write(self, context: ExportContext) -> Path:
        settings = context.settings
        paragraphs = split_paragraphs(
            context.transcript.segments,
            silence_seconds=settings.long_silence_seconds,
            use_silence=settings.detect_long_silences,
        ) if settings.split_paragraphs else [context.transcript.segments]

        blocks: list[str] = []
        for paragraph in paragraphs:
            text = paragraph_text(paragraph)
            if not text:
                continue
            speaker = paragraph[0].speaker
            if speaker:
                label = context.transcript.speakers.get(speaker, speaker)
                text = f"{label}: {text}"
            blocks.append(protect_neutrals(text))

        # A leading RLM makes the whole file open right-aligned in Notepad and
        # other editors that infer direction from the first strong character.
        content = RLM + "\r\n\r\n".join(blocks) + "\r\n"
        return write_text(target_path(context, self.extension), content)


class TimestampedTxtExporter:
    """One line per segment, prefixed with ``[MM:SS]``."""

    format = ExportFormat.TXT_TIMESTAMPED
    extension = "txt"

    def write(self, context: ExportContext) -> Path:
        lines: list[str] = []
        for segment in context.transcript.segments:
            text = segment.text.strip()
            if not text:
                continue
            speaker = segment.speaker
            if speaker:
                label = context.transcript.speakers.get(speaker, speaker)
                text = f"{label}: {text}"
            stamp = f"[{format_clock(segment.start)}]"
            # The stamp is Latin digits; the RLM after it keeps the bracket
            # pair on the correct side of the Hebrew that follows.
            lines.append(f"{stamp}{RLM} {protect_neutrals(text)}")

        content = RLM + "\r\n".join(lines) + "\r\n"
        path = target_path(context, self.extension)
        path = path.with_name(f"{context.stem}.timestamped.txt")
        return write_text(path, content)


class SrtExporter:
    """SubRip. CRLF line endings, 1-based indices, ``HH:MM:SS,mmm``."""

    format = ExportFormat.SRT
    extension = "srt"

    def write(self, context: ExportContext) -> Path:
        settings = context.settings
        cues = build_cues(
            context.transcript.segments,
            max_line_length=settings.subtitle_max_line_length,
            max_lines=settings.subtitle_max_lines,
            speakers=context.transcript.speakers,
        )
        blocks: list[str] = []
        for cue in cues:
            start = format_timestamp(cue.start, separator=",")
            end = format_timestamp(cue.end, separator=",")
            body = "\r\n".join(cue.lines)
            blocks.append(f"{cue.index}\r\n{start} --> {end}\r\n{body}\r\n")
        content = "\r\n".join(blocks)
        # No BOM: some hardware players choke on it in SRT.
        return write_text(target_path(context, self.extension), content, bom=False)


class VttExporter:
    """WebVTT. LF endings, ``HH:MM:SS.mmm``, RTL cue setting."""

    format = ExportFormat.VTT
    extension = "vtt"

    def write(self, context: ExportContext) -> Path:
        settings = context.settings
        cues = build_cues(
            context.transcript.segments,
            max_line_length=settings.subtitle_max_line_length,
            max_lines=settings.subtitle_max_lines,
            speakers=context.transcript.speakers,
        )
        lines = ["WEBVTT", "", "NOTE Generated by Tiktuv — local Hebrew transcription", ""]
        for cue in cues:
            start = format_timestamp(cue.start, separator=".")
            end = format_timestamp(cue.end, separator=".")
            # "direction:rl" tells conforming players to lay the cue out RTL
            # instead of relying on the first strong character.
            lines.append(f"{cue.index}")
            lines.append(f"{start} --> {end} direction:rl align:right")
            lines.extend(cue.lines)
            lines.append("")
        content = "\n".join(lines)
        return write_text(target_path(context, self.extension), content, bom=False)


class JsonExporter:
    """Full structured transcript, including word timestamps when present."""

    format = ExportFormat.JSON
    extension = "json"

    def write(self, context: ExportContext) -> Path:
        transcript = context.transcript
        payload = {
            "schema": "tiktuv.transcript/1",
            "job_id": transcript.job_id,
            "language": transcript.language,
            "model_id": transcript.model_id,
            "duration": round(transcript.duration, 3),
            "partial": transcript.partial,
            "created_at": transcript.created_at.isoformat() if transcript.created_at else None,
            "updated_at": transcript.updated_at.isoformat() if transcript.updated_at else None,
            "speakers": transcript.speakers,
            "settings": {
                "model_id": context.settings.model_id,
                "language": context.settings.language.value,
                "quality": context.settings.quality.value,
                "timestamps": context.settings.timestamps.value,
            },
            "segments": [
                {
                    "id": segment.id,
                    "start": round(segment.start, 3),
                    "end": round(segment.end, 3),
                    "text": segment.text,
                    "speaker": segment.speaker,
                    "edited": segment.edited,
                    "words": [
                        {
                            "text": word.text,
                            "start": round(word.start, 3),
                            "end": round(word.end, 3),
                            "probability": word.probability,
                        }
                        for word in segment.words
                    ],
                }
                for segment in transcript.segments
            ],
        }
        # ensure_ascii=False keeps Hebrew readable in the file rather than
        # escaping every character to \uXXXX.
        content = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
        return write_text(target_path(context, self.extension), content, bom=False)
