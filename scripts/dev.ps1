<#
.SYNOPSIS
    Start the Tiktuv backend and frontend for development.

.DESCRIPTION
    Launches the backend, waits for its handshake file, writes the session
    token into apps/frontend/.env.local so the Vite dev server can authenticate,
    then starts Vite. Ctrl+C stops both.

.PARAMETER Mock
    Use the deterministic mock ASR backend instead of the real model. Useful
    for UI work with no GPU and no model download.

.PARAMETER Port
    Backend port (default 8756).
#>
[CmdletBinding()]
param(
    [switch]$Mock,
    [int]$Port = 8756
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
Set-Location $repoRoot

$venvPython = Join-Path $repoRoot '.venv\Scripts\python.exe'
if (-not (Test-Path $venvPython)) {
    throw "Virtual environment not found. Run scripts\setup.ps1 first."
}

if ($Mock) {
    $env:TIKTUV_ASR_BACKEND = 'mock'
    Write-Host "Using the MOCK transcription backend (no real model)." -ForegroundColor Yellow
}
$env:TIKTUV_PORT = "$Port"
$env:TIKTUV_LOG_JSON = '0'

# The backend writes runtime.json into its data directory on startup.
$dataDir = Join-Path $env:LOCALAPPDATA 'Tiktuv'
$handshakePath = Join-Path $dataDir 'runtime.json'
Remove-Item $handshakePath -ErrorAction SilentlyContinue

Write-Host "Starting the backend on http://127.0.0.1:$Port ..." -ForegroundColor Cyan
$backend = Start-Process -FilePath $venvPython `
    -ArgumentList '-m', 'tiktuv', '--port', "$Port" `
    -PassThru -NoNewWindow

try {
    # Wait for the handshake so the token exists before Vite starts.
    $deadline = (Get-Date).AddSeconds(60)
    while (-not (Test-Path $handshakePath)) {
        if ($backend.HasExited) {
            throw "The backend exited during startup (exit code $($backend.ExitCode))."
        }
        if ((Get-Date) -gt $deadline) {
            throw "The backend did not start within 60 seconds."
        }
        Start-Sleep -Milliseconds 200
    }

    $handshake = Get-Content $handshakePath -Raw | ConvertFrom-Json
    Write-Host "Backend ready (version $($handshake.version), pid $($handshake.pid))." -ForegroundColor Green

    # The dev server proxies /api, so the frontend only needs the token.
    $envFile = Join-Path $repoRoot 'apps\frontend\.env.local'
    @(
        '# Generated by scripts/dev.ps1 — do not commit.',
        "VITE_TIKTUV_TOKEN=$($handshake.token)"
    ) | Set-Content -Path $envFile -Encoding utf8

    $env:TIKTUV_BACKEND_URL = "http://127.0.0.1:$Port"
    Write-Host "Starting the frontend on http://127.0.0.1:5173 ..." -ForegroundColor Cyan
    npm --prefix apps/frontend run dev
}
finally {
    if ($backend -and -not $backend.HasExited) {
        Write-Host "`nStopping the backend..." -ForegroundColor Cyan
        Stop-Process -Id $backend.Id -Force -ErrorAction SilentlyContinue
    }
}
