<#
.SYNOPSIS
    Install Tiktuv as a desktop application: a shortcut you can double-click.

.DESCRIPTION
    Creates "Tiktuv" on the Desktop (and optionally in the Start Menu) pointing
    at scripts\launch.ps1, with the Tiktuv icon and no console window.

    This is the lightweight route. It needs no Rust toolchain and no installer
    build — it runs the same backend and the same UI, in a dedicated app
    window. For a fully native MSI/NSIS installer, use scripts\build-windows.ps1
    instead (that path requires Rust and the VS C++ Build Tools).

.PARAMETER StartMenu
    Also add a Start Menu entry, so Tiktuv appears in search.

.PARAMETER DownloadModel
    Fetch the Hebrew model now (about 3 GB) instead of on first launch. Use
    this when preparing a machine for someone else, so their first
    transcription starts immediately.

.PARAMETER SkipModelPrompt
    Do not ask about the model. It will download automatically on first use.

.PARAMETER Uninstall
    Remove the shortcuts created by this script.
#>
[CmdletBinding()]
param(
    [switch]$StartMenu,
    [switch]$DownloadModel,
    [switch]$SkipModelPrompt,
    [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot

$desktop = [Environment]::GetFolderPath('Desktop')
$startMenuDir = Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs'
$shortcutName = 'Tiktuv.lnk'
$desktopShortcut = Join-Path $desktop $shortcutName
$startMenuShortcut = Join-Path $startMenuDir $shortcutName

# -- uninstall -------------------------------------------------------------
if ($Uninstall) {
    foreach ($path in @($desktopShortcut, $startMenuShortcut)) {
        if (Test-Path $path) {
            Remove-Item $path -Force
            Write-Host "Removed $path" -ForegroundColor Yellow
        }
    }
    Write-Host "`nShortcuts removed. Your transcripts and models are untouched," -ForegroundColor Green
    Write-Host "they remain in $env:LOCALAPPDATA\Tiktuv" -ForegroundColor Green
    exit 0
}

# -- prerequisites ---------------------------------------------------------
$venvPython = Join-Path $repoRoot '.venv\Scripts\python.exe'
if (-not (Test-Path $venvPython)) {
    throw "Tiktuv is not set up yet. Run scripts\setup.ps1 first."
}

$launcher = Join-Path $repoRoot 'scripts\launch.ps1'
if (-not (Test-Path $launcher)) { throw "Launcher not found at $launcher" }

# Build the UI if it is missing — the launcher needs it.
$distIndex = Join-Path $repoRoot 'apps\frontend\dist\index.html'
if (-not (Test-Path $distIndex)) {
    Write-Host "Building the interface (one time)..." -ForegroundColor Cyan
    Push-Location $repoRoot
    try {
        npm --prefix apps/frontend install
        npm --prefix apps/frontend run build
        if ($LASTEXITCODE -ne 0) { throw "frontend build failed" }
    } finally { Pop-Location }
}

# Generate the icon if it is missing.
$iconPath = Join-Path $repoRoot 'apps\desktop\src-tauri\icons\icon.ico'
if (-not (Test-Path $iconPath)) {
    Write-Host "Generating the application icon..." -ForegroundColor Cyan
    & $venvPython -m pip install --quiet pillow
    & $venvPython (Join-Path $repoRoot 'scripts\make-icon.py')
}

# -- create the shortcuts --------------------------------------------------
# The shortcut runs pythonw.exe directly: it hosts both the backend and the
# window, so the taskbar entry is Tiktuv's own rather than a browser's.
# pythonw has no console, so nothing flashes on launch.
$venvPythonw = Join-Path $repoRoot '.venv\Scripts\pythonw.exe'
if (-not (Test-Path $venvPythonw)) { $venvPythonw = $venvPython }

# Kept for troubleshooting and for machines with no WebView2 runtime:
# scripts\launch.ps1 still starts the backend and opens a browser window.
$vbsPath = Join-Path $repoRoot 'scripts\launch-silent.vbs'
@"
' Fallback launcher (browser window). Generated by install-desktop.ps1.
Set shell = CreateObject("WScript.Shell")
shell.Run "powershell.exe -NoProfile -ExecutionPolicy Bypass -File ""$launcher""", 0, False
"@ | Set-Content -Path $vbsPath -Encoding ASCII

function New-Shortcut([string]$path) {
    $shell = New-Object -ComObject WScript.Shell
    $shortcut = $shell.CreateShortcut($path)
    $shortcut.TargetPath = $venvPythonw
    $shortcut.Arguments = '-m tiktuv.app'
    $shortcut.WorkingDirectory = $repoRoot
    $shortcut.IconLocation = "$iconPath,0"
    $shortcut.Description = 'Tiktuv - local Hebrew transcription'
    $shortcut.WindowStyle = 1
    $shortcut.Save()
}

New-Shortcut $desktopShortcut
Write-Host "Created $desktopShortcut" -ForegroundColor Green

if ($StartMenu) {
    New-Shortcut $startMenuShortcut
    Write-Host "Created $startMenuShortcut" -ForegroundColor Green
}

# -- the Hebrew model ------------------------------------------------------
# Tiktuv downloads this automatically on first use, but doing it here means the
# person you hand the machine to can transcribe immediately.
$modelId = 'ivrit-ai/whisper-large-v3'
$modelsDir = Join-Path $env:LOCALAPPDATA 'Tiktuv\models'
$alreadyHave = Test-Path (Join-Path $modelsDir "models--$($modelId.Replace('/','--'))\snapshots")

$fetchNow = $DownloadModel
if (-not $fetchNow -and -not $SkipModelPrompt -and -not $alreadyHave) {
    Write-Host ""
    Write-Host "Tiktuv needs the Hebrew transcription model." -ForegroundColor Cyan
    Write-Host "  Model:       $modelId"
    Write-Host "  Download:    about 3 GB (about 6 GB on disk)"
    Write-Host "  Saved to:    $modelsDir"
    Write-Host "  Network use: this is the only step that needs the internet."
    Write-Host ""
    $answer = Read-Host "Download it now? It otherwise downloads on first use. [Y/n]"
    $fetchNow = ($answer -eq '' -or $answer -match '^[Yy]')
}

if ($fetchNow -and -not $alreadyHave) {
    Write-Host ""
    Write-Host "Downloading $modelId ..." -ForegroundColor Cyan
    Write-Host "This takes a while. It resumes if interrupted." -ForegroundColor DarkGray
    $env:TIKTUV_MODELS_DIR = $modelsDir
    & $venvPython -m tiktuv.fetch_model $modelId
    if ($LASTEXITCODE -ne 0) {
        Write-Warning "The model download did not finish. Tiktuv will retry automatically on first use."
    } else {
        Write-Host "Model ready." -ForegroundColor Green
    }
} elseif ($alreadyHave) {
    Write-Host "Hebrew model already present in $modelsDir" -ForegroundColor Green
}

Write-Host ""
Write-Host "Tiktuv is installed. Double-click the Tiktuv icon on your Desktop." -ForegroundColor Green
if (-not $fetchNow -and -not $alreadyHave) {
    Write-Host "The Hebrew model will download automatically the first time it is used." -ForegroundColor Cyan
}
Write-Host ""
Write-Host "To remove the shortcuts later:  scripts\install-desktop.ps1 -Uninstall" -ForegroundColor DarkGray
